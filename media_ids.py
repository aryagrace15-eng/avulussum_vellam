def get_comparison_meter() -> str:
    """Generates a Malayalam social standing progress bar."""
    percentage = random.randint(1, 12)
    filled = "█" * (percentage // 2)
    empty = "░" * (10 - (percentage // 2))
    metric = random.choice(MALAYALAM_COMPARISONS)
    
    return (
        f"📊 *സാമൂഹിക പദവി മീറ്റർ (Social Standing):*\n"
        f"[`{filled}{empty}`] *{percentage}%*\n"
        f"⚠️ *റിസൾട്ട്:* {metric}"
    )

